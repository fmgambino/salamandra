-- Vistas útiles para dashboard SuperAdmin
create or replace view public.v_superadmin_dashboard as
select
  (select count(*) from public.profiles) as users_count,
  (select count(*) from public.subscriptions where status in ('activa','prueba')) as subscribers_count,
  (select coalesce(sum(amount_usd),0) from public.subscriptions where status='activa') as income_usd,
  (select count(*) from public.devices where status='online') as devices_online,
  (select count(*) from public.support_tickets where status <> 'cerrado') as open_tickets,
  (select count(*) from public.inventory_items where stock <= min_stock) as low_stock_items;
