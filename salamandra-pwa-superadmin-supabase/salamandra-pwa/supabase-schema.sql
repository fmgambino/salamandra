create or replace function public.is_superadmin()
returns boolean language sql stable security definer as $$
  select exists(select 1 from public.profiles where id=auth.uid() and role='superadmin' and status='activo');
$$;

-- Políticas simples para desarrollo seguro
create policy "profiles_self_read" on public.profiles for select using (id=auth.uid() or public.is_superadmin());
create policy "profiles_superadmin_all" on public.profiles for all using (public.is_superadmin()) with check (public.is_superadmin());
create policy "plans_read_all" on public.plans for select using (true);
create policy "superadmin_all_plans" on public.plans for all using (public.is_superadmin()) with check (public.is_superadmin());
create policy "superadmin_all_support" on public.support_tickets for all using (public.is_superadmin()) with check (public.is_superadmin());
create policy "support_own" on public.support_tickets for select using (profile_id=auth.uid());
create policy "support_insert_own" on public.support_tickets for insert with check (profile_id=auth.uid());
create policy "superadmin_inventory" on public.inventory_items for all using (public.is_superadmin()) with check (public.is_superadmin());

